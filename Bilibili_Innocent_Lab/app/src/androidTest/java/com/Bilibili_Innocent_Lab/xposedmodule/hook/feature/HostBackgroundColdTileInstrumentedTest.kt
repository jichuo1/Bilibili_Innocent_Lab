package com.Bilibili_Innocent_Lab.xposedmodule.hook.feature

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Picture
import android.util.Log
import androidx.test.core.app.ActivityScenario
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.Bilibili_Innocent_Lab.xposedmodule.hook.hostui.background.HostBackgroundConfig
import com.Bilibili_Innocent_Lab.xposedmodule.hook.hostui.background.HostBackgroundDrawable
import com.Bilibili_Innocent_Lab.xposedmodule.hook.hostui.background.HostBackgroundPreset
import com.Bilibili_Innocent_Lab.xposedmodule.hook.hostui.background.HostBackgroundScene
import com.Bilibili_Innocent_Lab.xposedmodule.ui.activity.MainActivity
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.util.concurrent.ConcurrentHashMap

/**
 * 性能报告 P1-03：冷缓存下软件 Canvas 的交互绘制不在调用线程生成 tile，多个 Scene 对同键冷 miss 只生成一次；
 * 每个 tile 就绪推进采样版本；精确离屏导出仍同步得到完整内容。
 * 耗时只记录在日志（emulator 数据，不是真机结论）。
 */
@RunWith(AndroidJUnit4::class)
class HostBackgroundColdTileInstrumentedTest {
    private lateinit var scenario: ActivityScenario<MainActivity>
    private val renderThreads = ConcurrentHashMap.newKeySet<Thread>()

    @Before fun foreground() {
        scenario = ActivityScenario.launch(MainActivity::class.java)
        HostBackgroundScene.clearSharedCache()
        HostBackgroundScene.renderObserver = { _, thread -> renderThreads += thread }
    }

    @After fun restore() {
        HostBackgroundScene.renderObserver = null
        if (::scenario.isInitialized) scenario.close()
    }

    private fun await(what: String, timeoutMs: Long = 20_000, condition: () -> Boolean) {
        val deadline = System.nanoTime() + timeoutMs * 1_000_000
        while (!condition()) {
            if (System.nanoTime() > deadline) throw AssertionError("timeout waiting for $what")
            Thread.sleep(10)
        }
    }

    private fun config(veil: Int) = HostBackgroundConfig(HostBackgroundPreset.AURORA, veil = veil)

    private fun median(values: LongArray) = values.sorted()[values.size / 2]

    @Test fun coldSoftwareSamplingNeverRendersOnTheCallingThreadAndAdvancesTheSamplingVersion() {
        var caller: Thread? = null
        lateinit var drawable: HostBackgroundDrawable
        var versionBefore = 0L
        scenario.onActivity {
            caller = Thread.currentThread()
            drawable = HostBackgroundDrawable(config(41))
            drawable.setBounds(0, 0, 1080, 1920)
            versionBefore = drawable.samplingState
            val picture = Picture()
            val canvas = picture.beginRecording(1080, 1920)
            assertFalse("Picture recording is a software canvas", canvas.isHardwareAccelerated)
            drawable.draw(canvas)
            picture.endRecording()
            assertFalse("cold tiles are not ready yet: the caller was not blocked", drawable.isRasterReady)
        }
        await("visible tiles") { drawable.isRasterReady }
        await("pending flights") { HostBackgroundScene.flightStats().pending == 0 }
        assertTrue("tiles were generated by worker threads", renderThreads.isNotEmpty())
        assertFalse("no tile was generated on the drawing thread", renderThreads.contains(caller))
        assertNotEquals("sampling state must change when a tile is published", versionBefore, drawable.samplingState)
    }

    /** 冷缓存下同一视口：交互绘制（主线程、软件 Canvas）与旧行为（调用线程同步生成可见 tile）的调用线程耗时。 */
    @Test fun interactiveColdDrawIsOrdersOfMagnitudeCheaperThanBlockingGeneration() {
        val runs = 7
        val interactive = LongArray(runs)
        val blocking = LongArray(runs)
        for (round in -2 until runs) { // 前两轮预热类加载与线程池，不计入
            val index = round.coerceAtLeast(0)
            HostBackgroundScene.clearSharedCache()
            lateinit var cold: HostBackgroundDrawable
            var interactiveNs = 0L
            scenario.onActivity {
                cold = HostBackgroundDrawable(config(50 + round + 2))
                cold.setBounds(0, 0, 1080, 1920)
                val picture = Picture()
                val canvas = picture.beginRecording(1080, 1920)
                val started = System.nanoTime()
                cold.draw(canvas)
                interactiveNs = System.nanoTime() - started
                picture.endRecording()
            }
            await("pending flights") { HostBackgroundScene.flightStats().pending == 0 }
            HostBackgroundScene.clearSharedCache()
            var blockingNs = 0L
            scenario.onActivity {
                val exact = HostBackgroundDrawable(config(70 + round + 2), cacheEnabled = false)
                exact.setBounds(0, 0, 1080, 1920)
                val bitmap = Bitmap.createBitmap(1080, 1920, Bitmap.Config.ARGB_8888)
                val started = System.nanoTime()
                exact.draw(Canvas(bitmap))
                blockingNs = System.nanoTime() - started
                assertTrue("exact drawing completes before returning", exact.isRasterReady)
                bitmap.recycle()
            }
            if (round >= 0) { interactive[index] = interactiveNs; blocking[index] = blockingNs }
        }
        Log.i("ColdTile", "emulator (warm process, $runs cold runs): interactive draw median ${median(interactive) / 1000} us " +
            "max ${interactive.max() / 1000} us; blocking exact generation median ${median(blocking) / 1_000_000} ms min ${blocking.min() / 1_000_000} ms")
        assertTrue("interactive ${median(interactive)}ns vs blocking ${median(blocking)}ns",
            median(interactive) * 5 < median(blocking))
    }

    @Test fun twoScenesColdMissingTheSameTilesGenerateEachTileOnce() {
        val before = HostBackgroundScene.flightStats()
        lateinit var first: HostBackgroundDrawable
        lateinit var second: HostBackgroundDrawable
        scenario.onActivity {
            fun draw(): HostBackgroundDrawable = HostBackgroundDrawable(config(43)).also { drawable ->
                drawable.setBounds(0, 0, 1080, 1920)
                val picture = Picture()
                drawable.draw(picture.beginRecording(1080, 1920))
                picture.endRecording()
            }
            first = draw(); second = draw()
        }
        await("both scenes ready") { first.isRasterReady && second.isRasterReady }
        await("pending flights") { HostBackgroundScene.flightStats().pending == 0 }
        val after = HostBackgroundScene.flightStats()
        // 1080x1920、滚动 0：可见带 0、1，加前后各一带 → 4 个 key。
        assertEquals("each tile is generated once for both scenes", 4L, after.renders - before.renders)
        assertEquals(4L, after.created - before.created)
        assertTrue("the second scene joined the first scene's flights", after.joined - before.joined >= 4L)
        assertEquals(0L, after.rejected - before.rejected)
    }

    @Test fun exactOffscreenExportStaysSynchronousAndDoesNotUseTheSharedFlights() {
        val before = HostBackgroundScene.flightStats()
        scenario.onActivity {
            val exact = HostBackgroundDrawable(config(44), cacheEnabled = false)
            exact.setBounds(0, 0, 480, 960)
            val bitmap = Bitmap.createBitmap(480, 960, Bitmap.Config.ARGB_8888)
            exact.draw(Canvas(bitmap))
            assertTrue(exact.isRasterReady)
            val probe = bitmap.getPixel(240, 480)
            assertNotEquals("final scenery, not the fallback color", 0xffe8f3f1.toInt(), probe)
            bitmap.recycle()
        }
        val after = HostBackgroundScene.flightStats()
        assertEquals(0L, after.created - before.created)
        assertEquals(0L, after.renders - before.renders)
    }

    @Test fun movingTheViewportAwayCancelsUnstartedFlightsWithoutLeavingPendingWork() {
        lateinit var drawable: HostBackgroundDrawable
        scenario.onActivity {
            drawable = HostBackgroundDrawable(config(45))
            drawable.setBounds(0, 0, 1080, 1920)
            val picture = Picture()
            // 快速 fling：每一帧跳到新的世界坐标，旧视口的 tile 请求不应积压。
            for (frame in 0 until 40) {
                drawable.scrollOffset = frame * 5_000L
                drawable.draw(picture.beginRecording(1080, 1920))
                picture.endRecording()
            }
            assertTrue("pending is bounded", HostBackgroundScene.flightStats().pending <= 32)
        }
        await("pending flights drained") { HostBackgroundScene.flightStats().pending == 0 }
        await("final viewport tiles") { drawable.isRasterReady }
        val stats = HostBackgroundScene.flightStats()
        assertTrue("obsolete unstarted flights were cancelled instead of generated: $stats", stats.cancelled > 0)
        assertTrue("fewer tiles generated than requested: $stats", stats.renders < stats.created)
    }
}
